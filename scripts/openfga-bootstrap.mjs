/**
 * Creates an OpenFGA store, uploads the blog authorization model, backfills owner
 * tuples for existing blogs, and prints env vars to add to .env.local.
 *
 * Prerequisites: docker compose up (postgres + openfga on :8081)
 *
 * Usage: npm run openfga:bootstrap
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const require = createRequire(import.meta.url);

const { OpenFgaClient, OnDuplicateWrites } = await import("@openfga/sdk");
const { PrismaClient } = require("@prisma/client");

const apiUrl = process.env.OPENFGA_API_URL ?? "http://localhost:8081";

const blogAuthorizationModel = {
  schema_version: "1.1",
  type_definitions: [
    { type: "user" },
    {
      type: "blog",
      relations: {
        owner: { this: {} },
        viewer: {
          union: {
            child: [
              { this: {} },
              { computedUserset: { relation: "editor" } },
              { computedUserset: { relation: "admin" } },
              { computedUserset: { relation: "owner" } },
            ],
          },
        },
        editor: {
          union: {
            child: [
              { this: {} },
              { computedUserset: { relation: "admin" } },
              { computedUserset: { relation: "owner" } },
            ],
          },
        },
        admin: {
          union: {
            child: [{ this: {} }, { computedUserset: { relation: "owner" } }],
          },
        },
        can_view: { computedUserset: { relation: "viewer" } },
        can_edit: { computedUserset: { relation: "editor" } },
        can_delete: {
          union: {
            child: [
              { computedUserset: { relation: "owner" } },
              { computedUserset: { relation: "admin" } },
            ],
          },
        },
        can_share: {
          union: {
            child: [
              { computedUserset: { relation: "owner" } },
              { computedUserset: { relation: "admin" } },
            ],
          },
        },
      },
      metadata: {
        relations: {
          owner: { directly_related_user_types: [{ type: "user" }] },
          viewer: { directly_related_user_types: [{ type: "user" }] },
          editor: { directly_related_user_types: [{ type: "user" }] },
          admin: { directly_related_user_types: [{ type: "user" }] },
        },
      },
    },
  ],
};

async function main() {
  const client = new OpenFgaClient({ apiUrl });

  console.log(`OpenFGA API: ${apiUrl}`);

  const { id: storeId } = await client.createStore({
    name: "keycloak-saas-template",
  });
  console.log(`Created store: ${storeId}`);

  const storeClient = new OpenFgaClient({ apiUrl, storeId });

  const { authorization_model_id: modelId } =
    await storeClient.writeAuthorizationModel(blogAuthorizationModel);
  console.log(`Uploaded authorization model: ${modelId}`);

  const fga = new OpenFgaClient({
    apiUrl,
    storeId,
    authorizationModelId: modelId,
  });
  const prismaDir = resolve(root, "prisma");
  const databaseUrl =
    process.env.DATABASE_URL ?? `file:${resolve(prismaDir, "data/app.sqlite")}`;
  const prisma = new PrismaClient({
    datasources: { db: { url: databaseUrl } },
  });

  const blogs = await prisma.blog.findMany({
    select: { id: true, ownerKey: true, slug: true },
  });

  let backfilled = 0;
  for (const blog of blogs) {
    await fga.write({
      writes: [
        {
          user: `user:${blog.ownerKey}`,
          relation: "owner",
          object: `blog:${blog.id}`,
        },
      ],
    });
    backfilled += 1;
    console.log(`  owner tuple: blog:${blog.id} (${blog.slug})`);
  }

  await prisma.$disconnect();

  const envBlock = [
    "",
    "# OpenFGA (generated by npm run openfga:bootstrap)",
    `OPENFGA_API_URL=${apiUrl}`,
    `OPENFGA_STORE_ID=${storeId}`,
    `OPENFGA_AUTHORIZATION_MODEL_ID=${modelId}`,
    "",
  ].join("\n");

  console.log("\nAdd these lines to .env.local:\n");
  console.log(envBlock);

  const envLocalPath = resolve(root, ".env.local");
  if (existsSync(envLocalPath)) {
    const current = readFileSync(envLocalPath, "utf8");
    const hasPopulatedStoreId = /^OPENFGA_STORE_ID=\S/m.test(current);
    if (!hasPopulatedStoreId) {
      // Replace empty placeholder values written by start.sh, or append if absent
      let updated = current
        .replace(/^OPENFGA_API_URL=\s*$/m, `OPENFGA_API_URL=${apiUrl}`)
        .replace(/^OPENFGA_STORE_ID=\s*$/m, `OPENFGA_STORE_ID=${storeId}`)
        .replace(/^OPENFGA_AUTHORIZATION_MODEL_ID=\s*$/m, `OPENFGA_AUTHORIZATION_MODEL_ID=${modelId}`);
      if (!updated.includes(`OPENFGA_STORE_ID=${storeId}`)) {
        updated = updated.trimEnd() + envBlock;
      }
      writeFileSync(envLocalPath, updated);
      console.log(`Updated OpenFGA vars in ${envLocalPath}`);
    } else {
      console.log(
        `${envLocalPath} already has OPENFGA_STORE_ID — update manually if re-bootstrapping.`,
      );
    }
  }

  console.log(`\nDone. Backfilled ${backfilled} blog owner tuple(s).`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
